#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { build } from "esbuild";

const pkgRoot = process.cwd();
const outRoot = path.join(pkgRoot, "dist", "local-lib");

const copyPairs = [
  {
    from: "src/app/hookslens/panel.css",
    to: "src/app/hookslens/panel.css",
  },
];

const readme = `# hookslens local lib (copy template

Generated from repository root src/.

How to use:
1. Copy src/app/hookslens/page.jsx and src/app/hookslens/panel.css into your app's src/app/hookslens/ folder.
2. Keep importing the published runtime helpers and store from the package entrypoint:
  - import { hooksLensMiddleware, installFetchObserver, hooksLensStore } from "hookslens";
3. Open /hookslens in development.

Generated by:
npm run build:local-lib
`;

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function copyFileWithDirs(fromAbs, toAbs) {
  ensureDir(toAbs);
  fs.copyFileSync(fromAbs, toAbs);
}

async function generateLocalLibPage() {
  const entry = path.join(pkgRoot, "src", "app", "hookslens", "page.tsx");
  const outFile = path.join(outRoot, "src", "app", "hookslens", "page.jsx");
  const outTypes = path.join(outRoot, "src", "app", "hookslens", "page.d.ts");

  const result = await build({
    entryPoints: [entry],
    bundle: true,
    alias: {
      "@/lib/hookslens/store": "hookslens",
    },
    format: "esm",
    platform: "browser",
    target: ["es2020"],
    write: false,
    minify: false,
    sourcemap: false,
    loader: {
      ".css": "empty",
    },
    external: ["react", "react/jsx-runtime", "hookslens"],
    logLevel: "silent",
  });

  const jsOutput =
    result.outputFiles.find((f) => /\.(mjs|cjs|js|jsx)$/.test(f.path)) ??
    result.outputFiles.find((f) => f.text.includes("export default")) ??
    result.outputFiles[0];

  if (!jsOutput) {
    throw new Error("Failed to generate local-lib page.jsx (no JS output)");
  }

  const bundled = jsOutput.text
    .replace(/^\s*["']use client["'];?\s*/m, "")
    .replace(/^\s*import\s+["']\.\/panel\.css["'];?\s*/m, "");

  const finalCode = [
    '"use client";',
    'import "./panel.css";',
    "",
    "// Auto-generated from src/app/hookslens/page.tsx by build-local-lib.",
    bundled.trimStart(),
    "",
  ].join("\n");

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, finalCode, "utf8");
  fs.writeFileSync(
    outTypes,
    [
      'import type { JSX } from "react";',
      "",
      "declare function HooksLensPanel(): JSX.Element;",
      "",
      "export default HooksLensPanel;",
      "",
    ].join("\n"),
    "utf8",
  );
}

fs.rmSync(outRoot, { recursive: true, force: true });
fs.mkdirSync(outRoot, { recursive: true });

await generateLocalLibPage();

for (const pair of copyPairs) {
  const fromAbs = path.join(pkgRoot, pair.from);
  const toAbs = path.join(outRoot, pair.to);
  copyFileWithDirs(fromAbs, toAbs);
}

fs.writeFileSync(path.join(outRoot, "README.md"), readme, "utf8");

console.log(`Built copy template at: ${outRoot}`);
