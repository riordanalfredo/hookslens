#!/usr/bin/env node

import fs from "node:fs";
import path from "node:path";
import { build } from "esbuild";

const pkgRoot = process.cwd();
const outRoot = path.join(pkgRoot, "dist", "local-lib");

const copyPairs = [
  {
    from: "src/lib/hookslens/store.ts",
    to: "src/app/hookslens/lib/store.ts",
  },
  {
    from: "src/lib/hookslens/middleware.ts",
    to: "src/app/hookslens/lib/middleware.ts",
  },
  {
    from: "src/lib/hookslens/fetchObserver.ts",
    to: "src/app/hookslens/lib/fetchObserver.ts",
  },
  {
    from: "src/lib/hookslens/useHooksLens.ts",
    to: "src/app/hookslens/lib/useHooksLens.ts",
  },
  {
    from: "src/app/hookslens/panel.css",
    to: "src/app/hookslens/panel.css",
  },
  {
    from: "src/app/hookslens/api/hooks/route.ts",
    to: "src/app/hookslens/api/hooks/route.ts",
  },
  {
    from: "src/app/hookslens/api/stream/route.ts",
    to: "src/app/hookslens/api/stream/route.ts",
  },
];

const rewrites = [
  {
    file: "src/app/hookslens/lib/useHooksLens.ts",
    find: /@\/lib\/hookslens\/store/g,
    replace: "./store",
  },
  {
    file: "src/app/hookslens/api/hooks/route.ts",
    find: /@\/lib\/hookslens\/store/g,
    replace: "hookslens",
  },
  {
    file: "src/app/hookslens/api/stream/route.ts",
    find: /@\/lib\/hookslens\/store/g,
    replace: "hookslens",
  },
];

const readme = `# hookslens local lib (copy template

Generated from repository root src/.

How to use:
1. Copy the generated src/app/hookslens/ folder into your Next.js app's src/app/ tree.
2. The panel UI, routes, and local support code now live together under src/app/hookslens/.
3. Keep importing the published runtime helpers and store from the package entrypoint:
  - import { hooksLensMiddleware, installFetchObserver, hooksLensStore } from "hookslens";
4. Open /hookslens in development.

Generated by:
npm run build:local-lib
`;

function ensureDir(filePath) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
}

function copyFileWithDirs(fromAbs, toAbs) {
  ensureDir(toAbs);
  fs.copyFileSync(fromAbs, toAbs);
}

async function generateLocalLibPage() {
  const entry = path.join(pkgRoot, "src", "app", "hookslens", "page.tsx");
  const outFile = path.join(outRoot, "src", "app", "hookslens", "page.jsx");

  const result = await build({
    entryPoints: [entry],
    bundle: true,
    format: "esm",
    platform: "browser",
    target: ["es2020"],
    write: false,
    minify: false,
    sourcemap: false,
    loader: {
      ".css": "empty",
    },
    external: ["react", "react/jsx-runtime"],
    logLevel: "silent",
  });

  const jsOutput =
    result.outputFiles.find((f) => /\.(mjs|cjs|js|jsx)$/.test(f.path)) ??
    result.outputFiles.find((f) => f.text.includes("export default")) ??
    result.outputFiles[0];

  if (!jsOutput) {
    throw new Error("Failed to generate local-lib page.jsx (no JS output)");
  }

  const bundled = jsOutput.text
    .replace(/^\s*["']use client["'];?\s*/m, "")
    .replace(/^\s*import\s+["']\.\/panel\.css["'];?\s*/m, "");

  const finalCode = [
    '"use client";',
    'import "./panel.css";',
    "",
    "// Auto-generated from src/app/hookslens/page.tsx by build-local-lib.",
    bundled.trimStart(),
    "",
  ].join("\n");

  fs.mkdirSync(path.dirname(outFile), { recursive: true });
  fs.writeFileSync(outFile, finalCode, "utf8");
}

fs.rmSync(outRoot, { recursive: true, force: true });
fs.mkdirSync(outRoot, { recursive: true });

await generateLocalLibPage();

for (const pair of copyPairs) {
  const fromAbs = path.join(pkgRoot, pair.from);
  const toAbs = path.join(outRoot, pair.to);
  copyFileWithDirs(fromAbs, toAbs);
}

for (const rule of rewrites) {
  const target = path.join(outRoot, rule.file);
  const original = fs.readFileSync(target, "utf8");
  const next = original.replace(rule.find, rule.replace);
  fs.writeFileSync(target, next, "utf8");
}

fs.writeFileSync(path.join(outRoot, "README.md"), readme, "utf8");

console.log(`Built copy template at: ${outRoot}`);
